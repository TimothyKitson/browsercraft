Font::Font()
{
    struct Pixel { uint8_t r, g, b, a; };
    std::vector<Pixel> pixels(TEX_W * TEX_H, Pixel{ 255, 255, 255, 0 });

    const int glyphCount = LAST_CHAR - FIRST_CHAR + 1;
    for (int g = 0; g < glyphCount; ++g)
    {
        const int cellX = (g % COLUMNS) * CELL;
        const int cellY = (g / COLUMNS) * CELL;

        for (int col = 0; col < GLYPH_W; ++col)
        {
            const uint8_t bits = GLYPHS[g][col];
            for (int row = 0; row < GLYPH_H; ++row)
            {
                if (!(bits & (1 << row))) continue;
                const int x = cellX + col;
                const int y = cellY + row;
                pixels[y * TEX_W + x] = Pixel{ 255, 255, 255, 255 };
            }
        }
    }

    glGenTextures(1, &m_id);
    glBindTexture(GL_TEXTURE_2D, m_id);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, TEX_W, TEX_H, 0, GL_RGBA, GL_UNSIGNED_BYTE, pixels.data());
    glBindTexture(GL_TEXTURE_2D, 0);
}

Font::~Font()
{
    if (m_id) glDeleteTextures(1, &m_id);
}

void Font::glyphUV(char c, float& u0, float& v0, float& u1, float& v1)
{
    int code = static_cast<unsigned char>(c);
    if (code >= 'a' && code <= 'z') code -= 32; // fold lowercase to uppercase
    if (code < FIRST_CHAR || code > LAST_CHAR) code = FIRST_CHAR;

    const int index = code - FIRST_CHAR;
    const int cellX = (index % COLUMNS) * CELL;
    const int cellY = (index / COLUMNS) * CELL;

    u0 = static_cast<float>(cellX) / TEX_W;
    v0 = static_cast<float>(cellY) / TEX_H;
    u1 = static_cast<float>(cellX + GLYPH_W) / TEX_W;
    v1 = static_cast<float>(cellY + GLYPH_H) / TEX_H;
}
